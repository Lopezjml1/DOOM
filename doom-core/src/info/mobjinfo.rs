/// Static information for a map object type.
///
/// Each entry in the [`MOBJINFO`] table describes the immutable properties of a
/// particular map object type — its DoomEd editor number, animation states for
/// spawn/see/pain/melee/missile/death/raise, sound effects, movement speed,
/// collision dimensions, mass, contact damage, and behavior flags.
///
/// Original C: `mobjinfo_t` (info.h lines 1305-1331).
#[derive(Debug, Clone, Copy)]
pub struct MobjInfo {
    /// DoomEd number for map editor placement. -1 means the object is not
    /// directly spawnable from a map (e.g., projectiles, effects).
    pub doomednum: i32,
    /// State when first spawned.
    pub spawnstate: StateNum,
    /// Initial health points.
    pub spawnhealth: i32,
    /// State entered when the monster spots a player.
    pub seestate: StateNum,
    /// Sound played when the monster spots a player.
    pub seesound: SfxEnum,
    /// Tics before the monster can first attack after seeing a player.
    pub reactiontime: i32,
    /// Sound played when the monster attacks.
    pub attacksound: SfxEnum,
    /// State entered when the monster takes pain.
    pub painstate: StateNum,
    /// Probability (0-255) of entering pain state when damaged.
    pub painchance: i32,
    /// Sound played when the monster is in pain.
    pub painsound: SfxEnum,
    /// Melee attack state (S_NULL = no melee attack).
    pub meleestate: StateNum,
    /// Missile/ranged attack state (S_NULL = no ranged attack).
    pub missilestate: StateNum,
    /// State entered on death.
    pub deathstate: StateNum,
    /// State entered on extreme death (gibbing).
    pub xdeathstate: StateNum,
    /// Sound played on death.
    pub deathsound: SfxEnum,
    /// Movement speed. Raw integer for monsters, N*FRACUNIT for projectiles.
    pub speed: i32,
    /// Collision radius in fixed-point (e.g., 20*FRACUNIT).
    pub radius: i32,
    /// Collision height in fixed-point (e.g., 56*FRACUNIT).
    pub height: i32,
    /// Mass value — affects thrust received from damage.
    pub mass: i32,
    /// Contact damage amount (for projectiles and charging attacks).
    pub damage: i32,
    /// Sound played when the monster is active/wandering.
    pub activesound: SfxEnum,
    /// Behavior flags (MobjFlags bitfield stored as raw u32).
    pub flags: u32,
    /// State for resurrection by Archvile (S_NULL = cannot be raised).
    pub raisestate: StateNum,
}

